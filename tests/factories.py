"""Structure-file factories shared by the tests."""

from __future__ import annotations


def pdb_atom_line(
    serial: int,
    name: str,
    residue: str,
    chain: str,
    resseq: int,
    x: float,
    y: float,
    z: float,
    element: str,
    record: str = "ATOM",
) -> str:
    """Build one spec-compliant PDB coordinate line.

    Column layout (1-based, inclusive) as written by RCSB files:
    ``1-6 record | 7-11 serial | 12 blank | 13-16 name | 17 altLoc |
    18-20 resName | 21 blank | 22 chain | 23-26 resSeq | 27 iCode |
    31-38 x | 39-46 y | 47-54 z | 55-60 occupancy | 61-66 tempFactor |
    77-78 element``
    """
    return (
        f"{record:<6s}"                    # indices  0-5   (cols 1-6)
        f"{serial:5d} "                    # indices  6-11  (cols 7-12)
        f"{name:<4s}"                      # indices 12-15  (cols 13-16)
        f" "                               # index   16     (col 17, altLoc)
        f"{residue:>3s}"                   # indices 17-19  (cols 18-20)
        f" "                               # index   20     (col 21, blank)
        f"{chain:1s}"                      # index   21     (col 22, chainID)
        f"{resseq:4d}"                     # indices 22-25  (cols 23-26)
        f"    "                            # indices 26-29  (iCode + blank)
        f"{x:8.3f}{y:8.3f}{z:8.3f}"        # indices 30-53  (cols 31-54)
        f"  1.00 20.00"                    # indices 54-65  (cols 55-66)
        f"          "                      # indices 66-75  (cols 67-76)
        f"{element:>2s}"                   # indices 76-77  (cols 77-78)
    )


#: Backbone atoms of a poly-alanine model, repeated for every residue.
BACKBONE = {
    "N": (0.000, 0.000, 0.000),
    "CA": (1.458, 0.000, 0.000),
    "C": (2.009, 1.420, 0.000),
    "O": (3.228, 1.620, 0.000),
}


def build_pdb_lines(residues: int = 3, chain: str = "A") -> list[str]:
    """Return the lines of a small poly-alanine PDB file (+ water + Zn)."""
    lines = ["HEADER    SYNTHETIC TEST STRUCTURE", "REMARK    generated by tests"]
    serial = 0
    for residue_index in range(1, residues + 1):
        for name, (x, y, z) in BACKBONE.items():
            serial += 1
            lines.append(
                pdb_atom_line(serial, name, "ALA", chain, residue_index,
                              x + residue_index * 3.0, y, z, name[0])
            )
    serial += 1
    lines.append(pdb_atom_line(serial, "O", "HOH", chain, residues + 2,
                               10.0, 0.0, 0.0, "O", record="HETATM"))
    serial += 1
    lines.append(pdb_atom_line(serial, "ZN", "ZN", chain, residues + 3,
                               5.0, 5.0, 5.0, "ZN", record="HETATM"))
    lines.append("END")
    return lines


def build_cif_text(residues: int = 3, chain: str = "A") -> str:
    """Return the same structure as an mmCIF document."""
    header = [
        "data_TEST",
        "_entry.id TEST",
        "loop_",
        "_atom_site.group_PDB",
        "_atom_site.id",
        "_atom_site.type_symbol",
        "_atom_site.label_atom_id",
        "_atom_site.label_comp_id",
        "_atom_site.label_asym_id",
        "_atom_site.auth_asym_id",
        "_atom_site.auth_seq_id",
        "_atom_site.Cartn_x",
        "_atom_site.Cartn_y",
        "_atom_site.Cartn_z",
        "_atom_site.label_alt_id",
    ]
    rows: list[str] = []
    serial = 0
    for residue_index in range(1, residues + 1):
        for name, (x, y, z) in BACKBONE.items():
            serial += 1
            rows.append(
                f"ATOM {serial} {name[0]} {name} ALA {chain} {chain} "
                f"{residue_index} {x + residue_index * 3.0:.3f} {y:.3f} {z:.3f} ."
            )
    serial += 1
    rows.append(f"HETATM {serial} O O HOH {chain} {chain} {residues + 2} 10.000 0.000 0.000 .")
    serial += 1
    rows.append(f"HETATM {serial} ZN ZN ZN {chain} {chain} {residues + 3} 5.000 5.000 5.000 .")
    rows.append("#")
    return "\n".join([*header, *rows])
